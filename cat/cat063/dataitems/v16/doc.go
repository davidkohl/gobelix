// Package v16 provides data item implementations for ASTERIX Category 063 version 1.6.
//
// This package implements all data items defined in the EUROCONTROL ASTERIX
// Category 063 (SDPS Service Status Messages) specification version 1.6.
// Each data item type implements the asterix.DataItem interface with
// Encode, Decode, and Validate methods.
//
// Data items are named according to their ASTERIX designation (e.g., I063/010
// becomes DataSourceIdentifier, I063/015 becomes ServiceIdentification).
