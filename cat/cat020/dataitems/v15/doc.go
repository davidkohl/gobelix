// Package v15 provides data item implementations for ASTERIX Category 020 version 1.5.
//
// This package implements all data items defined in the EUROCONTROL ASTERIX
// Category 020 (Multilateration Target Reports) specification version 1.5.
// Each data item type implements the asterix.DataItem interface with
// Encode, Decode, and Validate methods.
//
// Data items are named according to their ASTERIX designation (e.g., I020/010
// becomes DataSourceIdentifier, I020/020 becomes TargetReportDescriptor).
