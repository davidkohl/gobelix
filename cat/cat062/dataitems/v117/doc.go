// This package implements data items defined in the EUROCONTROL ASTERIX
// Category 062 (SDPS Track Messages) specification version 1.17.
// Each data item type implements the asterix.DataItem interface with
// Encode, Decode, and Validate methods.
//
// Data items are named according to their ASTERIX designation (e.g., I062/010
// becomes DataSourceIdentifier, I062/040 becomes TrackNumber).
