// Package v132 provides data item implementations for ASTERIX Category 048 version 1.32.
//
// This package implements all data items defined in the EUROCONTROL ASTERIX
// Category 048 (Monoradar Target Reports) specification version 1.32.
// Each data item type implements the asterix.DataItem interface with
// Encode, Decode, and Validate methods.
//
// Data items are named according to their ASTERIX designation (e.g., I048/010
// becomes DataSourceIdentifier, I048/020 becomes TargetReportDescriptor).
package v132
